/**
 * Reports how much of the vendored contract is implemented, grouped by area, and
 * writes docs/api-coverage.md. Fails when a previously-implemented operation has
 * regressed to a 501 stub.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
  createManagementApiRouter,
  DELIBERATE_DIVERGENCES,
  EMPTY_SETTINGS_OPERATIONS,
  PLANNED_AREAS,
  PLANNED_OPERATIONS,
} from '@crombolo/api-management'
import { createBackOfficePaths, createExtensionRegistry } from '@crombolo/backoffice-host'
import { connect, cromboloPlan, migrate } from '@crombolo/data'
import { PublishedCache } from '@crombolo/render'
import { createDeps, createPublishedContentSource, loadConfig } from '@crombolo/server'

const ROOT = join(import.meta.dir, '..')
const OUT = join(ROOT, 'docs/api-coverage.md')

// Built from the real composition root, with a throwaway database, so the report
// counts every handler that actually ships rather than only the stateless ones.
const paths = createBackOfficePaths()
const db = await connect({ dialect: 'sqlite', file: ':memory:' })
await migrate(db, cromboloPlan)
const router = createManagementApiRouter({
  deps: createDeps({
    config: loadConfig(),
    paths,
    extensions: createExtensionRegistry(join(ROOT, 'apps/site')),
    db,
    cache: new PublishedCache(createPublishedContentSource(db)),
  }),
})

interface AreaCoverage {
  area: string
  total: number
  implemented: number
}

const byArea = new Map<string, AreaCoverage>()
for (const op of router.operations) {
  const area = op.area ?? '(none)'
  const entry = byArea.get(area) ?? { area, total: 0, implemented: 0 }
  entry.total += 1
  if (router.has(op.operationId)) entry.implemented += 1
  byArea.set(area, entry)
}

const areas = [...byArea.values()].sort(
  (a, b) => b.implemented - a.implemented || b.total - a.total || a.area.localeCompare(b.area),
)
const total = router.operations.length
const implemented = router.implementedCount
const stubbed = EMPTY_SETTINGS_OPERATIONS.filter((op) => router.has(op)).length
const pct = ((implemented / total) * 100).toFixed(1)
const unbuilt = router.operations.filter((op) => !router.has(op.operationId))
const divergent = unbuilt.filter((op) => DELIBERATE_DIVERGENCES[op.operationId])
const missing = unbuilt.filter((op) => !DELIBERATE_DIVERGENCES[op.operationId])
const row = (op: (typeof unbuilt)[number], note: string) =>
  `| \`${op.operationId}\` | \`${op.method.toUpperCase()} ${op.path.replace('/umbraco/management/api/v1', '')}\` | ${note} |`

const lines = [
  '# API coverage',
  '',
  '<!-- Generated by `bun run coverage:api`. Do not edit. -->',
  '',
  `**${implemented} / ${total} operations implemented (${pct}%)** — ${implemented - stubbed} real, ${stubbed} answering an honest empty page for areas not yet built (\`handlers/settings-stubs.ts\`).`,
  '',
  '| Area | Implemented | Total |',
  '| --- | --- | --- |',
  ...areas.map((a) => `| ${a.area} | ${a.implemented} | ${a.total} |`),
  '',
  '## Deliberate divergences',
  '',
  'These answer 501 on purpose (`packages/api-management/src/divergences.ts`).',
  '',
  '| Operation | Route | Why |',
  '| --- | --- | --- |',
  ...divergent.map((op) => row(op, DELIBERATE_DIVERGENCES[op.operationId] as string)),
  '',
  '## Not built yet',
  '',
  ...(missing.length === 0
    ? ['Nothing: every other operation is implemented.']
    : [
        '| Operation | Route | Planned in |',
        '| --- | --- | --- |',
        ...missing.map((op) =>
          row(
            op,
            PLANNED_OPERATIONS[op.operationId] ?? PLANNED_AREAS[op.area ?? ''] ?? 'no story yet',
          ),
        ),
      ]),
  '',
]
writeFileSync(OUT, lines.join('\n'))

console.log(`${implemented}/${total} operations implemented (${pct}%)`)
console.log(`${divergent.length} deliberate divergences, ${missing.length} not built yet`)
console.log(`wrote ${OUT.replace(`${ROOT}/`, '')}`)

await db.close()

const baseline = Number(Bun.env.CROMBOLO_COVERAGE_BASELINE ?? 0)
if (implemented < baseline) {
  console.error(`coverage regressed: ${implemented} < baseline ${baseline}`)
  process.exit(1)
}
